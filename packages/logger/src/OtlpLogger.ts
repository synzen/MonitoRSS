import { logs } from '@opentelemetry/api';
import { OTLPLogExporter } from '@opentelemetry/exporter-logs-otlp-http';
import { resourceFromAttributes } from '@opentelemetry/resources';
import { BatchLogRecordProcessor, LoggerProvider } from '@opentelemetry/sdk-logs';
import { OpenTelemetryTransportV3 } from '@opentelemetry/winston-transport';
import winston from 'winston';
import { AbstractLogger, LoggerOptions } from './AbstractLogger';

interface OtlpLoggerOptions extends LoggerOptions {
  /**
   * The OTLP gateway base URL (e.g. https://otlp-gateway-prod-us-east-2.grafana.net/otlp).
   * Logs are posted to `${endpoint}/v1/logs`.
   */
  endpoint: string
  /**
   * The OTLP_HEADERS connection value generated by the Grafana Cloud portal's
   * OpenTelemetry tile (e.g. "Authorization=Basic <base64(instanceId:token)>").
   */
  headers: string
  /**
   * The service name emitted as the `service.name` resource attribute. Keep it
   * identical to the previous Datadog `service` value so log-based filters keep working.
   */
  service: string
}

// One provider per process; a second OtlpLogger instance (e.g. across tests)
// reuses the provider configured by the first.
let providerConfigured = false;

export default class OtlpLogger extends AbstractLogger<OtlpLoggerOptions> {
  protected createLogger(options: OtlpLoggerOptions) {
    const { endpoint, service } = options;
    // Accepts the portal's shell snippet (export OTEL_EXPORTER_OTLP_HEADERS="Authorization=Basic X"),
    // the unquoted value (Authorization=Basic X), or a pre-built header value (Basic X).
    const authorization =
      /Authorization="([^"]+)"/.exec(options.headers)?.[1] ??
      /Authorization=(Basic\s+[^\s"]+)/.exec(options.headers)?.[1] ??
      /Authorization=(\S+)/.exec(options.headers)?.[1];
    if (!authorization) {
      console.warn('OtlpLogger: no "Authorization=" entry found in the provided headers; OTLP writes will fail');
    }

    if (!providerConfigured) {
      const provider = new LoggerProvider({
        resource: resourceFromAttributes({
          'service.name': service,
          ...(options.env && { 'deployment.environment.name': options.env }),
        }),
        // Default batching (1s) keeps the loss window on process exit tight
        // while avoiding one HTTP request per log line.
        processors: [
          new BatchLogRecordProcessor({
            exporter: new OTLPLogExporter({
              url: `${endpoint}/v1/logs`,
              ...(authorization && { headers: { Authorization: authorization } }),
            }),
          }),
        ],
      });
      logs.setGlobalLoggerProvider(provider);
      providerConfigured = true;
    }

    return winston.createLogger({
      exitOnError: false,
      silent: !this.shouldLog,
      transports: [
        new OpenTelemetryTransportV3(),
      ],
      exceptionHandlers: [
        new winston.transports.Console(),
      ],
    });
  }
}
